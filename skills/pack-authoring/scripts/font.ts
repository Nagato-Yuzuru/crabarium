/** The ink pixels of `char` as [x, y] from its top left; none for a space or an unknown character. */
export function glyph(char: string): readonly (readonly [number, number])[] {
  const rows = GLYPHS[char.toUpperCase()] ?? []
  return rows.flatMap((row, y) => [...row].flatMap((bit, x) => (bit === '#' ? [[x, y] as const] : [])))
}

/** The width in font pixels of `text`, with one pixel between glyphs. */
export function textWidth(text: string): number {
  return text.length === 0 ? 0 : text.length * (GLYPH_WIDTH + 1) - 1
}
