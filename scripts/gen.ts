// Writes the files made from other files, or with --check, fails when one is
// out of date:
//   schema/pack.schema.json   from hooks/core/pack/schema.ts
//   hooks/packs.generated.ts  from packs/<name>/pack.json and pack.css
//   hooks/vendor/css.js       from scripts/vendor/css.ts and its packages
// The check also runs each fixture in tests/fixtures/packs.ts through Ajv, a
// full JSON Schema validator, so the published schema means what the mod's
// own validator reads from it.

import { Ajv2020 } from 'ajv/dist/2020.js'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'
import { build } from 'vite-plus'

import { packSchema } from '../hooks/core/pack/schema.ts'
import { packFixtures } from '../tests/fixtures/packs.ts'

const root = join(import.meta.dirname, '..')
const isCheck = process.argv.includes('--check')

async function builtinPacks(): Promise<string> {
  const dir = join(root, 'packs')
  const names = (await readdir(dir, { withFileTypes: true })).filter(d => d.isDirectory()).map(d => d.name)
  const entries = await Promise.all(
    names
      .toSorted()
      // The data, not the file's layout: a formatter run on packs/ must not make this file out of date.
      .map(async name => {
        const data: unknown = JSON.parse(await readFile(join(dir, name, 'pack.json'), 'utf8'))
        const css = await readFile(join(dir, name, 'pack.css'), 'utf8').catch(() => null)
        const source = css === null ? { json: JSON.stringify(data) } : { json: JSON.stringify(data), css }
        return `  ${JSON.stringify(name)}: ${JSON.stringify(source)},`
      }),
  )
  return [
    '// Generated by `pnpm gen` from packs/<name>/pack.json and pack.css. Do not edit.',
    '// The engine cannot import JSON, so the built-in packs come in as text.',
    "import type { PackSource } from './core/pack/load.ts'",
    '',
    'export const builtinPacks: Readonly<Record<string, PackSource>> = {',
    ...entries,
    '}',
    '',
  ].join('\n')
}

// The engine loads no node_modules, so each package that the mod imports is
// built into one ES module under hooks/vendor/. The mod's own code stays
// source: `claude plugin validate` reads it, and it fails on bundled code.
async function vendor(entry: string): Promise<string> {
  const result = await build({
    configFile: false,
    logLevel: 'silent',
    build: { write: false, minify: false, lib: { entry: join(root, entry), formats: ['es'] } },
  })
  // A library build gives one bundle for each format; this one has one format.
  const bundles = Array.isArray(result) ? result : [result]
  const [bundle] = bundles
  if (bundles.length !== 1 || bundle === undefined || !('output' in bundle)) throw new Error(`${entry}: the build did not give one bundle`)
  const [chunk, ...rest] = bundle.output
  if (rest.length > 0) throw new Error(`${entry}: the build gave more than one file`)
  return `// Generated by \`pnpm gen\` from ${entry}. Do not edit.\n${chunk.code}`
}

const outputs: ReadonlyArray<readonly [path: string, make: () => Promise<string>]> = [
  ['schema/pack.schema.json', async () => `${JSON.stringify(packSchema, null, 2)}\n`],
  ['hooks/packs.generated.ts', builtinPacks],
  ['hooks/vendor/css.js', async () => vendor('scripts/vendor/css.ts')],
]

// Each output: its problem with --check, or null when it is current.
async function sync(path: string, make: () => Promise<string>): Promise<string | null> {
  const want = await make()
  const file = join(root, path)
  const have = await readFile(file, 'utf8').catch(() => null)
  if (have === want) return null
  if (isCheck) return `${path} is out of date: run pnpm gen`
  await writeFile(file, want)
  return null
}

const problems = (await Promise.all(outputs.map(([path, make]) => sync(path, make)))).filter(p => p !== null)

if (isCheck) {
  const validate = new Ajv2020({ strict: true, allErrors: true }).compile(packSchema)
  for (const fixture of packFixtures) {
    const accepted = validate(fixture.json)
    if (accepted !== fixture.schemaValid) {
      problems.push(
        `fixture "${fixture.name}": Ajv says ${accepted ? 'valid' : 'invalid'}, the fixture says ${fixture.schemaValid ? 'valid' : 'invalid'}`,
      )
    }
  }
}

if (problems.length > 0) {
  console.error(problems.join('\n'))
  process.exit(1)
}
